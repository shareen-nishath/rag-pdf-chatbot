import os
import shutil
import uuid

# Store the active PDF's RAG components
rag_data = {
    "chain": None,
    "name": None,
    "pages": 0,
    "chunks": 0,
    "db": None
}


# Process uploaded PDF
def process_pdf(pdf_file):
    if pdf_file is None:
        return "⚠️ Please upload a PDF first.", []

    try:
        pdf_path = pdf_file.name

        # Load PDF pages
        loader = PyPDFLoader(pdf_path)
        documents = loader.load()

        if not documents or not any(
            doc.page_content.strip() for doc in documents
        ):
            return "⚠️ No readable text found. Try a text-based PDF.", []

        # Split into chunks
        splitter = RecursiveCharacterTextSplitter(
            chunk_size=500,
            chunk_overlap=100
        )
        chunks = splitter.split_documents(documents)

        if not chunks:
            return "⚠️ No text chunks could be created.", []

        # Create a fresh vector store for this PDF
        collection_name = "pdf_" + uuid.uuid4().hex[:12]

        vectorstore = Chroma.from_documents(
            documents=chunks,
            embedding=embeddings,
            collection_name=collection_name
        )

        # Create retriever
        retriever = vectorstore.as_retriever(
            search_kwargs={"k": 4}
        )

        # Format retrieved text
        def format_docs(docs):
            return "\n\n".join(
                f"Page {doc.metadata.get('page', 0) + 1}:\n"
                f"{doc.page_content}"
                for doc in docs
            )

        # Prompt
        prompt = ChatPromptTemplate.from_template("""
You are a helpful PDF assistant.

Answer using only the retrieved context.
If the answer is not present, say:
"I couldn't find the answer in the uploaded PDF."

Give clear, accurate answers.
Mention page numbers when useful.

Context:
{context}

Question:
{question}

Answer:
""")

        # Create RAG chain
        chain = (
            {
                "context": retriever | format_docs,
                "question": RunnablePassthrough()
            }
            | prompt
            | llm
            | StrOutputParser()
        )

        # Save current PDF's components
        rag_data["chain"] = chain
        rag_data["name"] = os.path.basename(pdf_path)
        rag_data["pages"] = len(documents)
        rag_data["chunks"] = len(chunks)
        rag_data["db"] = vectorstore

        status = f"""
✅ PDF processed successfully!

📄 **File:** {rag_data['name']}

📑 **Pages:** {len(documents)}

🧠 **Text chunks:** {len(chunks)}

You can now ask questions about your document.
"""

        return status, []

    except Exception as e:
        return f"❌ Error processing PDF: {type(e).__name__}: {str(e)}", []


# Answer user questions
def chat_with_pdf(question, history):
    history = history or []

    if not question or not question.strip():
        history.append({
            "role": "assistant",
            "content": "Please enter a question."
        })
        return history, ""

    if rag_data["chain"] is None:
        history.append({
            "role": "user",
            "content": question
        })
        history.append({
            "role": "assistant",
            "content": "Please upload and process a PDF first."
        })
        return history, ""

    history.append({
        "role": "user",
        "content": question
    })

    try:
        answer = rag_data["chain"].invoke(question.strip())
    except Exception as e:
        answer = f"Error: {type(e).__name__}: {str(e)}"

    history.append({
        "role": "assistant",
        "content": answer
    })

    return history, ""


